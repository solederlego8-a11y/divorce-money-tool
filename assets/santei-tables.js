// 説明書の手順どおり「近い方の目盛り」を選ぶ。
// ちょうど中間の場合の扱いは説明書に明記がないため、小さい方を採用し、
// その旨を呼び出し側で明示できるよう tie フラグを返す（2回目で原典を
// 再確認したが、中間の場合のルールは説明書のどこにも記載がない）。
function nearestScale(ticks, incomeManYen) {
if (!ticks ||!ticks.length) return null;
var best = ticks[0], bestDiff = Math.abs(incomeManYen - ticks[0]), tie = false;
for (var i = 1; i < ticks.length; i++) {
var d = Math.abs(incomeManYen - ticks[i]);
if (d < bestDiff - 1e-9) { best = ticks[i]; bestDiff = d; tie = false;}
else if (Math.abs(d - bestDiff) <= 1e-9 && ticks[i]!== best) { tie = true;}
}
return { scale: best, tie: tie};
}

